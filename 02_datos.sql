/* ---------------------------------------------------------------------
   9. Verificación: todo debe dar 0 diferencias
   --------------------------------------------------------------------- */
SELECT N'Inventario vs. movimientos' AS verificacion, COUNT(*) AS diferencias
FROM dbo.Inventario i
CROSS APPLY (SELECT ISNULL(SUM(CASE m.tipo WHEN N'SALIDA' THEN -m.cantidad ELSE m.cantidad END), 0) AS calculada
             FROM dbo.MovimientoInventario m WHERE m.idProducto = i.idProducto) c
WHERE i.existencia <> c.calculada
UNION ALL
SELECT N'Pedido vs. detalle', COUNT(*)
FROM dbo.Pedido pe
CROSS APPLY (SELECT SUM(d.cantidad * d.precioUnitario) AS st, SUM(d.cantidad * d.descuentoUnitario) AS ds
             FROM dbo.DetallePedido d WHERE d.idPedido = pe.idPedido) x
WHERE pe.subtotal <> x.st OR pe.descuentoTotal <> x.ds
UNION ALL
SELECT N'Pago vs. total del pedido', COUNT(*)
FROM dbo.Pedido pe JOIN dbo.Pago pa ON pa.idPedido = pe.idPedido
WHERE pa.monto <> pe.total
UNION ALL
SELECT N'Estado actual vs. último del historial', COUNT(*)
FROM dbo.Pedido pe
CROSS APPLY (SELECT TOP (1) h.idEstado FROM dbo.HistorialEstadoPedido h
             WHERE h.idPedido = pe.idPedido ORDER BY h.fecha DESC, h.idHistorial DESC) u
WHERE u.idEstado <> pe.idEstado;
GO

